/**
 * Every tunable number in the adaptive processing system, in one place.
 *
 * Two rules for this file:
 *
 * 1. No magic numbers elsewhere. If a threshold matters, it lives here with a
 *    comment explaining where it came from.
 * 2. Constants that describe the C++ core (bytes per row, hash-set load factor)
 *    are not guesses — they are read off the implementation and confirmed by
 *    measurement. Each one names its source so it can be re-checked when the
 *    core changes.
 *
 * Measurements below were taken on an M-series Mac with Emscripten 3.1.74, over
 * a 516 MB / 7.9 M-row CSV generated by `cleaner/tools/gen_csv.py` (4 numeric or
 * date columns, 2 categorical, 1 dropped constant). Re-run with
 * `cleaner/build/memtest.cjs` after changing the core.
 */

const MB = 1024 * 1024;
const GB = 1024 * MB;

// ── Chunking ──────────────────────────────────────────────────────────────────

/**
 * Chunk size bounds. The scanner is a push parser whose output is provably
 * independent of chunk size (see the `chunk_boundaries_are_invisible` test), so
 * these are about memory and UI responsiveness, not correctness.
 *
 * Bigger chunks buy almost nothing: only rows straddling a boundary get copied,
 * which at 4 MB over 516 MB is ~128 rows out of 7.9 million. The ceiling exists
 * because the chunk buffer is a single allocation inside WASM memory, and the
 * floor because very small chunks multiply the JS↔WASM call overhead.
 */
export const MIN_CHUNK_BYTES = 4 * MB;
export const MAX_CHUNK_BYTES = 64 * MB;

// ── Memory budget tiers ───────────────────────────────────────────────────────

export interface MemoryTier {
  /** Upper bound of the tier, in GB of estimated device memory. */
  maxDeviceMemoryGB: number;
  targetMemoryBytes: number;
  chunkBytes: number;
}

/**
 * Budget by estimated device memory. Deliberately a small fraction of RAM: the
 * browser is one tab among many, and the numbers feeding this are coarse.
 *
 * A caveat that shapes the whole design: `navigator.deviceMemory` is defined to
 * report RAM rounded *down* to a power of two and then clamped to at most 8.
 * A 64 GB workstation and an 8 GB laptop both report exactly 8. The tiers above
 * 8 GB are therefore unreachable from that API alone — they exist for callers
 * that can supply a real figure (`deviceMemoryOverrideGB`), which is what a
 * future desktop build would do.
 */
// The 8 GB rung was 512 MB and got raised to 1 GB after measurement: a 516 MB
// CSV of ordinary shape really uses 727 MB of WASM heap, so the old budget
// advised against a file that demonstrably works. 1 GB is still only ~12 % of
// an 8 GB machine, which keeps the posture conservative while no longer
// crying wolf on the most common case this tool exists for.
export const MEMORY_TIERS: MemoryTier[] = [
  { maxDeviceMemoryGB: 4, targetMemoryBytes: 256 * MB, chunkBytes: 8 * MB },
  { maxDeviceMemoryGB: 8, targetMemoryBytes: 1 * GB, chunkBytes: 16 * MB },
  { maxDeviceMemoryGB: 16, targetMemoryBytes: 1 * GB, chunkBytes: 32 * MB },
  { maxDeviceMemoryGB: Infinity, targetMemoryBytes: 1.5 * GB, chunkBytes: 64 * MB },
];

/** Used when no memory signal is available at all. Matches the 4 GB tier. */
export const UNKNOWN_DEVICE_TARGET_BYTES = 256 * MB;
export const UNKNOWN_DEVICE_CHUNK_BYTES = 8 * MB;

/** Floor and ceiling applied after every other rule, including the tiers. */
export const MIN_TARGET_MEMORY_BYTES = 128 * MB;
export const MAX_TARGET_MEMORY_BYTES = 2 * GB;

/**
 * Fraction of `performance.memory.jsHeapSizeLimit` we allow the budget to reach.
 *
 * Worth being precise about what that number is: it is the *JavaScript* heap
 * ceiling, and in Chrome WebAssembly memory is allocated outside it, so it does
 * not directly bound the WASM heap. It is used here as a conservative signal —
 * a process with a small JS heap ceiling is a constrained process — and as a
 * real bound on the JS-side copies, which do land in that heap.
 */
export const JS_HEAP_SAFETY_FACTOR = 0.5;

/**
 * How far past the target we let actual usage drift before aborting. The target
 * is a soft aim; this is the wall.
 */
export const MEMORY_SAFETY_FACTOR = 1.5;

/** Fraction of the budget at which the monitor starts warning. */
export const MEMORY_WARNING_FRACTION = 0.8;

// ── WASM limits ───────────────────────────────────────────────────────────────

/**
 * wasm32 addresses memory with 32-bit pointers, so 4 GiB is the architectural
 * ceiling — not a policy we chose, and not raisable without `-sMEMORY64`.
 */
export const WASM32_ADDRESS_LIMIT_BYTES = 4 * GB;

/**
 * Highest heap we will plan for. Below the architectural limit because the last
 * stretch is where allocation failures actually happen, and a failed growth
 * mid-file loses the whole run.
 */
export const WASM_PLANNING_LIMIT_BYTES = 3 * GB;

/**
 * Ratio of real WASM heap to the sum of the column and hash-set sizes computed
 * below. Measured: predicted 491 MB, observed 727 MB over the reference file.
 * Covers allocator bookkeeping, fragmentation, and growth overshoot.
 */
export const WASM_ALLOCATOR_OVERHEAD = 1.5;

// ── Core memory model ─────────────────────────────────────────────────────────
//
// These describe what the C++ core stores per row. Source: `Column` in
// cleaner/include/chartbay/table.hpp.

/** `std::vector<double> values` (8) + `std::vector<uint8_t> mask` (1). */
export const BYTES_PER_NUMERIC_ROW = 9;

/** Dates are stored as a day serial in the same `values` array. */
export const BYTES_PER_DATE_ROW = 9;

/** `std::vector<int32_t> codes` (4) + mask (1). The dictionary is bounded. */
export const BYTES_PER_CATEGORICAL_ROW = 5;

/**
 * A text column keeps a `std::string` per row. libc++ stores up to 22 bytes
 * inline in a 24-byte object; longer values add a heap allocation. 24 + mask +
 * an allowance for the characters themselves.
 */
export const TEXT_STRING_OVERHEAD_BYTES = 25;

/**
 * Transient cost of profiling: `compute_stats` copies the present values of one
 * column into a vector and sorts it. Only one column at a time, and never in
 * scan mode.
 */
export const BYTES_PER_SORTED_VALUE = 8;

// ── Global duplicate detection ────────────────────────────────────────────────
//
// Source: `RowHashSet` in cleaner/src/table.cpp.

/** One 64-bit hash per slot, in a flat array. No per-entry allocation. */
export const DUPLICATE_BYTES_PER_SLOT = 8;

/** `RowHashSet` grows when (size + 1) * 4 >= slots * 3. */
export const DUPLICATE_LOAD_FACTOR = 0.75;

/** Slot count is always a power of two, so the table can mask instead of modulo. */
export const DUPLICATE_SLOTS_ARE_POWERS_OF_TWO = true;

// ── Row estimation ────────────────────────────────────────────────────────────

/**
 * Bytes read from the head of the file to estimate the average row size. Small
 * enough to be instant, large enough that a few long rows do not dominate.
 */
export const PREFLIGHT_SAMPLE_BYTES = 256 * 1024;

/** Below this, preflight is pointless — everything is safe. */
export const PREFLIGHT_MIN_FILE_BYTES = 8 * MB;

// ── Warning thresholds ────────────────────────────────────────────────────────

/**
 * Estimated memory as a fraction of the budget, mapped to a status.
 * Below WARNING → safe; between → warning; above NOT_RECOMMENDED → the estimate
 * says this will not fit.
 */
export const WARNING_THRESHOLDS = {
  warning: 0.7,
  notRecommended: 1.0,
} as const;

/**
 * Estimates are estimates. A file only gets *blocked* when the projection
 * exceeds the budget by this much AND runs past the WASM planning limit, so an
 * inaccurate row estimate cannot lock a user out of their own data.
 */
export const HARD_BLOCK_MULTIPLIER = 1.0;

// ── Time ──────────────────────────────────────────────────────────────────────

/**
 * Observed WASM throughput on the reference machine, used only to show an
 * expected duration. Real speed varies with column mix and hardware; treat it
 * as an order of magnitude.
 */
export const WASM_THROUGHPUT_BYTES_PER_SECOND = 31 * MB;

/** Beyond this, the UI mentions how long it will take. */
export const SLOW_PROCESSING_WARNING_SECONDS = 30;

const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const origin = process.env.CLEANER_TEST_URL || 'http://127.0.0.1:5057';
(async () => {
const browser = await chromium.launch({headless:true,channel:'chrome'});
const page = await browser.newPage({viewport:{width:1280,height:1000},acceptDownloads:true});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto(origin + '/limpiador');
await page.evaluate(()=>{window.showSaveFilePicker=undefined;});
await page.locator('#dc-file').setInputFiles({name:'sucio.csv',mimeType:'text/csv',buffer:Buffer.from('nombre,CUIT,importe\n Ana  Pérez ,20-12345678-6,12\n Ana  Pérez ,20-12345678-6,12\nLuis,20123456789,NA\n')});
await page.locator('#dc-import').click();
await page.waitForFunction(()=>document.querySelector('#dc-status').textContent.includes('Perfil completo')||document.querySelector('#dc-status').textContent.startsWith('Error'),null,{timeout:30000});
console.log('import',await page.locator('#dc-status').textContent());
console.log('summary',await page.locator('#dc-summary').textContent());
if(await page.locator('#dc-results').isHidden())throw new Error('Import failed');
await page.locator('#dc-duplicates').check();
await page.locator('#dc-preview').click();
await page.waitForFunction(()=>document.querySelector('#dc-status').textContent.includes('Vista previa actualizada'));
await page.locator('#dc-apply').click();
await page.waitForFunction(()=>document.querySelector('#dc-status').textContent.includes('Cambios aplicados'));
let downloadPromise=page.waitForEvent('download');
await page.locator('#dc-download').click();
let download=await downloadPromise;
const csv = await fs.readFile(await download.path(),'utf8');
assert.equal(csv, '\uFEFFnombre,CUIT,importe\r\nAna Pérez,20123456786,12\r\nLuis,20123456789,NA\r\n');
console.log('CSV round-trip OK');
downloadPromise=page.waitForEvent('download');
await page.locator('#dc-audit').click();
download=await downloadPromise;
const audit=JSON.parse(await fs.readFile(await download.path(),'utf8'));
assert.equal(audit.review.rowsOut, 2); assert.equal(audit.changes.length, 3);
console.log('Audit matches exported changes');
await page.locator('#dc-undo').click();
await page.waitForFunction(()=>document.querySelector('#dc-status').textContent.includes('valores originales'));
console.log('undo',await page.locator('#dc-status').textContent());
assert.equal(await page.locator('#dc-download').isDisabled(), true);
if (process.env.CLEANER_SCREENSHOT) await page.screenshot({path:process.env.CLEANER_SCREENSHOT,fullPage:true});
// XLSX generated with Python/openpyxl for an independent producer.
await page.locator('#dc-file').setInputFiles(path.resolve(__dirname, '../../../cleaner/tests/fixtures/import.xlsx'));
await page.waitForFunction(()=>document.querySelector('#dc-sheet').options.length===2);
await page.locator('#dc-sheet').selectOption('Datos');
await page.locator('#dc-import').click();
await page.waitForFunction(()=>document.querySelector('#dc-status').textContent.includes('Perfil completo')||document.querySelector('#dc-status').textContent.startsWith('Error'),null,{timeout:30000});
console.log('excel',await page.locator('#dc-status').textContent(),await page.locator('#dc-summary').textContent());
console.log('errors',JSON.stringify(errors));
if(errors.length || (await page.locator('#dc-status').textContent()).startsWith('Error'))throw new Error('Browser errors');
await page.locator('#dc-apply').click();
await page.waitForFunction(()=>document.querySelector('#dc-status').textContent.includes('Cambios aplicados'));
await page.locator('#dc-handoff').click();
await page.waitForURL(origin + '/econometria');
await page.waitForFunction(()=>document.querySelector('#qb-filename')?.textContent.includes('import-limpio.csv'),null,{timeout:30000});
console.log('Disk Blob handoff to Econometria OK');
await page.goto(origin + '/limpiador?motor=estadistico');
await page.locator('#cl-file').setInputFiles({name:'legacy.csv',mimeType:'text/csv',buffer:Buffer.from('x,y\n1,2\n2,3\n3,4')});
await page.waitForFunction(()=>document.querySelector('#cl-status').textContent.startsWith('Listo:'),null,{timeout:30000});
assert.equal(errors.length, 0);
console.log('Legacy statistical cleaner OK');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
